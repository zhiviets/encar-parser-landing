def clean_latin(text):
    """Перевести частые слова и выбросить то, что осталось по-корейски."""
    if not text:
        return None
    text = str(text)
    for ko, en in WORDS:
        text = text.replace(ko, en)
    words = [w for w in text.split() if not HANGUL.search(w)]
    result = " ".join(words).strip(" -/")
    return result or None


def lookup(table, value):
    if not value:
        return None
    value = str(value).strip()
    if value in table:
        return table[value]
    return None if HANGUL.search(value) else value


def region(address):
    if not address:
        return None
    first = str(address).split()[0]
    for ko, ru in REGION.items():
        if first.startswith(ko):
            return ru
    return None


def release(year_month):
    ym = re.sub(r"\D", "", str(year_month or ""))
    if len(ym) < 6:
        return None
    month = int(ym[4:6])
    if not 1 <= month <= 12:
        return ym[:4]
    return f"{MONTHS[month - 1]} {ym[:4]}"
